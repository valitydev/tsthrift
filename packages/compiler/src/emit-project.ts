import { parseBinaryMode } from "./binary-mode.ts";
import type { I64Mode } from "./i64-mode.ts";
import { parseI64Mode } from "./i64-mode.ts";
import { emitModels } from "./emit-models.ts";
import { emitRootIndex } from "./emit-root-index.ts";
import { emitProgramServices } from "./emit-services.ts";
import { emitProgramIndex, emitServicesRegistry } from "./emit-service-registry.ts";
import { emitMetadata } from "./metadata/emit-metadata.ts";
import {
  emitMetadataLoader,
  emitModuleMetadata,
  emitNamespaceMetadataLoader,
} from "./metadata/emit-split-metadata.ts";
import type { Program, Schema } from "./schema.ts";
import { validateOutput } from "./validate-output.ts";
import { validateSchema } from "./validate-schema.ts";

/** A generated artifact: a POSIX path relative to the output root and its text. */
export interface GeneratedFile {
  path: string;
  content: string;
}

export interface ProjectOptions {
  /** Emit TypeScript models, metadata modules, and loaders (default: true). */
  models?: boolean;
  /** Emit service factories and the registry; requires models (default: true). */
  services?: boolean;
  lowerCaseMethods?: boolean;
  /** Emit monolithic `metadata.json` (default: only when models are not emitted). */
  metadataJson?: boolean;
  i64?: I64Mode;
  binary?: BinaryMode;
  /** Local namespace re-exported from the root index. */
  main?: string;
}

export interface ResolvedProjectOptions {
  models: boolean;
  services: boolean;
  lowerCaseMethods: boolean;
  metadataJson: boolean;
  i64: I64Mode;
  binary: BinaryMode;
  main?: string;
}

/** Applies defaults and rejects unknown i64/binary modes. */
export function resolveProjectOptions(options: ProjectOptions = {}): ResolvedProjectOptions {
  const models = options.models ?? true;
  return {
    models,
    services: models && options.services !== false,
    lowerCaseMethods: Boolean(options.lowerCaseMethods),
    metadataJson: options.metadataJson ?? !models,
    i64: parseI64Mode(options.i64),
    binary: parseBinaryMode(options.binary),
    main: options.main,
  };
}

/** Validates the schema and the names it would generate under the selected options. */
export function validateProject(schema: Schema, options: ResolvedProjectOptions): void {
  validateSchema(schema);
  if (options.models) validateOutput(schema, options.services, options.lowerCaseMethods);
}

function hasServices(program: Program): boolean {
  return Boolean(program.ast.service && Object.keys(program.ast.service).length > 0);
}

/** Entry points of the generated package: the root index, namespace indexes, and loaders. */
export function projectEntries(schema: Schema): string[] {
  return [
    "index.ts",
    ...schema.localPrograms.flatMap((program) => [
      `${program.name}/index.ts`,
      `${program.name}/load-metadata.ts`,
    ]),
  ];
}

/**
 * Emits every generated artifact in memory. The schema must already pass `validateProject` with
 * the same options. Nothing is read from or written to the environment.
 */
export function emitProject(schema: Schema, options: ResolvedProjectOptions): GeneratedFile[] {
  const { i64, binary, lowerCaseMethods } = options;
  const files: GeneratedFile[] = [];
  const add = (path: string, content: string) => files.push({ path, content });

  if (options.models) {
    const build = { metadataVersion: 1, i64, lowerCaseMethods, binary } as const;
    add(
      "build.ts",
      `export const TSTHRIFT_BUILD: { readonly metadataVersion: 1; readonly i64: ${JSON.stringify(i64)}; readonly lowerCaseMethods: ${lowerCaseMethods}; readonly binary: ${JSON.stringify(binary)} } = ${JSON.stringify(build)};\n`,
    );
    for (const program of schema.localPrograms) {
      const dir = program.name;
      add(`${dir}/models.ts`, emitModels(program, i64, binary));
      add(
        `${dir}/metadata.ts`,
        emitModuleMetadata(program, { i64, lowerCaseMethods, binary }).content,
      );
      add(`${dir}/load-metadata.ts`, emitNamespaceMetadataLoader(program));

      const programServices = options.services && hasServices(program);
      if (programServices) {
        for (const file of emitProgramServices(program, i64, lowerCaseMethods, binary)) {
          add(`${dir}/services/${file.relativePath}`, file.content);
        }
        add(`${dir}/services/index.ts`, emitProgramIndex(program));
      }

      const indexLines = [
        "// Generated by tsthrift. Do not edit.",
        'export * from "./models.js";',
        'export { TSTHRIFT_BUILD } from "../build.js";',
        'export { thriftMetadata } from "./metadata.js";',
        'export { loadThriftMetadata } from "./load-metadata.js";',
      ];
      if (programServices) indexLines.push('export * from "./services/index.js";');
      add(`${dir}/index.ts`, `${indexLines.join("\n")}\n`);
    }

    add("metadata.ts", emitMetadataLoader(schema));
    const registry = options.services && schema.localPrograms.some(hasServices);
    if (registry) add("services.ts", emitServicesRegistry(schema));
    add("index.ts", emitRootIndex(schema, options.main, registry));

    const tsconfig = {
      compilerOptions: {
        target: "ES2022",
        module: "NodeNext",
        moduleResolution: "NodeNext",
        declaration: true,
        isolatedDeclarations: true,
        strict: true,
        skipLibCheck: true,
        resolveJsonModule: true,
      },
    };
    add("tsconfig.json", JSON.stringify(tsconfig, null, 2) + "\n");
  }

  if (options.metadataJson) {
    add("metadata.json", emitMetadata(schema, { i64, lowerCaseMethods, binary }));
  }
  return files;
}
