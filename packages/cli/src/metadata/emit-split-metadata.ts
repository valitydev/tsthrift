import type { Metadata } from "@vality/tsthrift";
import type { Program, Schema } from "../compiler/load-schema.ts";
import { getTransitiveDependencies } from "./dependencies.ts";

export interface EmittedModuleMetadata {
  name: string;
  filename: string;
  content: string;
}

/** Emits an individual TypeScript module containing the parsed Thrift AST metadata. */
export function emitModuleMetadata(
  program: Program,
  build?: Metadata["build"],
): EmittedModuleMetadata {
  const meta = {
    metadataVersion: 1,
    build,
    name: program.name,
    path: program.path,
    ast: program.ast,
  };
  const body = JSON.stringify(meta, null, 2);

  const lines = [
    "// Generated by tsthrift. Do not edit.",
    'import type { Metadata } from "@vality/tsthrift";',
    "",
    `export const thriftMetadata: Metadata = ${body};`,
    "",
    "export default thriftMetadata;",
    "",
  ];

  return {
    name: program.name,
    filename: "metadata.ts",
    content: lines.join("\n"),
  };
}

/** Emits a namespace loader using the runtime's retryable dependency cache. */
export function emitNamespaceMetadataLoader(program: Program): string {
  const deps = getTransitiveDependencies(program);
  const entries = deps.map((dep) => {
    const specifier =
      dep.name === program.name
        ? "./metadata.js"
        : dep.external
          ? (dep.external.metadataPath ?? dep.external.importPath)
          : `../${dep.name}/metadata.js`;
    return `  ${JSON.stringify(dep.name)}: () => import(${JSON.stringify(specifier)}),`;
  });
  return [
    "// Generated by tsthrift. Do not edit.",
    'import { createNamespaceLoader, type Metadata } from "@vality/tsthrift";',
    "export const loadThriftMetadata: () => Promise<Metadata[]> = createNamespaceLoader({",
    ...entries,
    "});",
    "",
  ].join("\n");
}

/**
 * Emits the root metadata index module delegating to each namespace's local loader.
 */
export function emitMetadataLoader(schema: Schema): string {
  const namespaces = JSON.stringify(
    [...schema.localPrograms, ...schema.externalPrograms].map((program) => program.name).sort(),
  );
  const lines = [
    "// Generated by tsthrift. Do not edit.",
    'import { createMetadataLoader, type Metadata } from "@vality/tsthrift";',
    "",
    `export const THRIFT_NAMESPACES: readonly ${namespaces} = ${namespaces};`,
    "",
  ];

  if (schema.externalPrograms.length > 0) {
    lines.push("export interface ExternalNamespaceDescriptor {");
    lines.push("  readonly name: string;");
    lines.push("  readonly package: string;");
    lines.push("  readonly importPath: string;");
    lines.push("  readonly isExternal: true;");
    lines.push("}");
    lines.push("");
    lines.push("export const EXTERNAL_NAMESPACES: Record<string, ExternalNamespaceDescriptor> = {");
    for (const p of schema.externalPrograms) {
      const ext = p.external!;
      lines.push(`  ${JSON.stringify(p.name)}: {`);
      lines.push(`    name: ${JSON.stringify(p.name)},`);
      lines.push(`    package: ${JSON.stringify(ext.package ?? "")},`);
      lines.push(`    importPath: ${JSON.stringify(ext.importPath)},`);
      lines.push("    isExternal: true,");
      lines.push("  },");
    }
    lines.push("};");
    lines.push("");
  }

  lines.push(
    "export const loadThriftMetadataByNamespaces: (namespace: (typeof THRIFT_NAMESPACES)[number] | readonly (typeof THRIFT_NAMESPACES)[number][]) => Promise<Metadata[]> = createMetadataLoader({",
  );

  for (const program of schema.localPrograms) {
    lines.push(
      `  ${JSON.stringify(program.name)}: () => import("./${program.name}/load-metadata.js").then((m) => m.loadThriftMetadata()),`,
    );
  }

  for (const program of schema.externalPrograms) {
    const specifier = program.external!.metadataPath ?? program.external!.importPath;
    lines.push(`  ${JSON.stringify(program.name)}: () => import(${JSON.stringify(specifier)}),`);
  }
  lines.push("});", "");

  return lines.join("\n");
}
